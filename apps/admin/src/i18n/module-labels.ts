export function localizeModuleLabel(
  locale: Locale,
  label: string
): string {
  if (locale === 'en') {
    return englishLabels[label] ?? label;
  }

  if (locale === 'ar') {
    return arabicLabels[label] ?? label;
  }

  return label;
}
